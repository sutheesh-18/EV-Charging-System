// frontend/scripts/generate-assets.mjs
// Scans public/models and public/images/vehicles and writes src/data/assetManifest.ts
// so you never have to edit the AVAILABLE lists by hand.
//
// Run from the frontend folder:   npm run assets
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { join, extname, basename } from "node:path";

const root = process.cwd();
const modelsDir = join(root, "public", "models");
const imagesDir = join(root, "public", "images", "vehicles");
const outFile = join(root, "src", "data", "assetManifest.ts");

const list = (dir, ext) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => extname(f).toLowerCase() === ext)
        .map((f) => basename(f, extname(f)))
    : [];

const modelIds = list(modelsDir, ".glb").sort();
const imageIds = list(imagesDir, ".jpg").sort();

// warn about files the app will not pick up
if (existsSync(imagesDir)) {
  readdirSync(imagesDir)
    .filter((f) => [".png", ".jpeg", ".webp"].includes(extname(f).toLowerCase()))
    .forEach((f) => console.warn(`! ${f}: only .jpg images are used. Convert or rename it.`));
}
if (existsSync(modelsDir)) {
  readdirSync(modelsDir)
    .filter((f) => [".gltf", ".fbx", ".obj"].includes(extname(f).toLowerCase()))
    .forEach((f) => console.warn(`! ${f}: only .glb models are used. Convert it first.`));
}

// generic-* files are the fallbacks, not cars
const cars = (ids) => ids.filter((id) => !id.startsWith("generic-"));

const body = `// AUTO-GENERATED by scripts/generate-assets.mjs. Do not edit by hand.
// Run "npm run assets" after adding or removing files in public/.

export const MODEL_IDS: string[] = ${JSON.stringify(cars(modelIds), null, 2)};

export const IMAGE_IDS: string[] = ${JSON.stringify(cars(imageIds), null, 2)};
`;

writeFileSync(outFile, body);

console.log(`3D models found:  ${cars(modelIds).length}  ->  ${cars(modelIds).join(", ") || "none"}`);
console.log(`2D images found:  ${cars(imageIds).length}  ->  ${cars(imageIds).join(", ") || "none"}`);

const needed = ["suv", "sedan", "hatchback", "mpv"];
const missingModels = needed.filter((b) => !modelIds.includes(`generic-${b}`));
const missingImages = needed.filter((b) => !imageIds.includes(`generic-${b}`));
if (missingModels.length) console.log(`Missing generic models: ${missingModels.map((b) => `generic-${b}.glb`).join(", ")}`);
if (missingImages.length) console.log(`Missing generic images: ${missingImages.map((b) => `generic-${b}.jpg`).join(", ")}`);
console.log(`Wrote ${outFile}`);